import { readdirSync, writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/**
 * Regenerates `src/data/toolContent/index.ts` from whatever per-tool files exist.
 *
 * The content files are authored one-per-tool so parallel work never collides on
 * a shared registry; this reassembles the registry afterwards, and fails loudly
 * if a tool in the catalogue has no content file — a tool page with no content
 * section has almost no indexable prose, which is the exact problem this whole
 * content layer exists to fix, so it should break the build rather than ship.
 */
const root = fileURLToPath(new URL('..', import.meta.url));
const dir = `${root}src/data/toolContent`;

const toolsSrc = readFileSync(`${root}src/data/tools.ts`, 'utf8');
const rawBlock = toolsSrc.slice(toolsSrc.indexOf('const RAW_TOOLS'), toolsSrc.indexOf('export const TOOLS'));
const ids = [...rawBlock.matchAll(/^\s*\['([a-z0-9-]+)',/gm)].map((m) => m[1]);

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .sort();

const missing = ids.filter((id) => !files.includes(id));
const orphan = files.filter((f) => !ids.includes(f));

const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const header = `import type { ToolContent } from '../toolContentTypes';
`;
const imports = files.map((f) => `import { ${camel(f)}Content } from './${f}';`).join('\n');
const entries = files.map((f) => `  '${f}': ${camel(f)}Content,`).join('\n');

const out = `${header}${imports}

/**
 * Long-form content per tool id. GENERATED by \`npm run content-index\` from the
 * one-file-per-tool sources in this directory — edit those, not this file.
 *
 * Every tool in \`src/data/tools.ts\` must have an entry; the generator script
 * fails if one is missing, because a tool page without its content section has
 * almost no indexable prose.
 */
export const TOOL_CONTENT: Record<string, ToolContent> = {
${entries}
};

export function getToolContent(id: string): ToolContent | null {
  return TOOL_CONTENT[id] ?? null;
}
`;

writeFileSync(`${dir}/index.ts`, out);

console.log(`Wrote toolContent/index.ts — ${files.length} of ${ids.length} tools have content.`);
if (orphan.length) console.warn(`  WARN orphan content files (no matching tool): ${orphan.join(', ')}`);
if (missing.length) {
  console.error(`  MISSING content for ${missing.length} tool(s): ${missing.join(', ')}`);
  if (process.argv.includes('--strict')) process.exit(1);
}
